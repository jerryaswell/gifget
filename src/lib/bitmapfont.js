const ROWS = Object.fromEntries(Object.entries(GLYPHS).map(([ch, rows]) => [ch, rows.split(' ')]));

export const glyph = (ch) => ROWS[ch.toUpperCase()] ?? ROWS['?'];

/**
 * The word as a white sprite, px high or as near as whole-pixel scaling gets,
 * and no wider than maxW. Each glyph is 5 columns and a 1-column gap.
 */
export function bitmapText(word, px, maxW = Infinity) {
  const chars = [...word];
  const cols = Math.max(1, chars.length * 6 - 1);
  let scale = Math.max(1, Math.round(px / 7));
  scale = Math.max(1, Math.min(scale, Math.floor(maxW / cols)));
  const pad = scale;
  const img = raster(cols * scale + pad * 2, 7 * scale + pad * 2, [255, 255, 255], 0);
  chars.forEach((ch, n) => {
    glyph(ch).forEach((row, y) => {
      for (let x = 0; x < 5; x++) {
        if (row[x] !== '1') continue;
        for (let j = 0; j < scale; j++) {
          for (let i = 0; i < scale; i++) {
            const px0 = pad + (n * 6 + x) * scale + i;
            const py0 = pad + y * scale + j;
            img.data[(py0 * img.w + px0) * 4 + 3] = 255;
          }
        }
      }
    });
  });
  return img;
}
